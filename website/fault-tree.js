// Get fault tree by manufacturer key
function getFaultTree(manufacturer) {
  return FAULT_TREES[manufacturer] || null;
}

// Get all available manufacturers
function getManufacturers() {
  return Object.keys(FAULT_TREES).map(key => ({
    key,
    name: FAULT_TREES[key].name,
    icon: FAULT_TREES[key].icon,
    boardCount: FAULT_TREES[key].boards.length
  }));
}

// Get symptoms for a manufacturer
function getSymptoms(manufacturer) {
  const tree = FAULT_TREES[manufacturer];
  return tree ? tree.symptoms : [];
}

// Search across all fault trees
function searchFaultTrees(query) {
  const q = query.toLowerCase();
  const results = [];

  for (const [key, tree] of Object.entries(FAULT_TREES)) {
    for (const symptom of tree.symptoms) {
      const matchesSymptom = symptom.symptom.toLowerCase().includes(q);
      const matchingSteps = symptom.steps.filter(step =>
        step.text.toLowerCase().includes(q) ||
        step.hint.toLowerCase().includes(q) ||
        step.nets.some(n => n.toLowerCase().includes(q))
      );

      if (matchesSymptom || matchingSteps.length > 0) {
        results.push({
          manufacturer: key,
          manufacturerName: tree.name,
          manufacturerIcon: tree.icon,
          symptom: symptom.symptom,
          steps: matchingSteps.length > 0 ? matchingSteps : symptom.steps
        });
      }
    }
  }

  // Also search generic fault trees
  for (const symptom of GENERIC_FAULT_TREE) {
    const matchesSymptom = symptom.symptom.toLowerCase().includes(q);
    const matchingSteps = symptom.steps.filter(step =>
      step.text.toLowerCase().includes(q) ||
      step.hint.toLowerCase().includes(q) ||
      step.nets.some(n => n.toLowerCase().includes(q))
    );

    if (matchesSymptom || matchingSteps.length > 0) {
      results.push({
        manufacturer: 'generic',
        manufacturerName: 'Generic',
        manufacturerIcon: '🔧',
        symptom: symptom.symptom,
        steps: matchingSteps.length > 0 ? matchingSteps : symptom.steps
      });
    }
  }

  return results;
}

