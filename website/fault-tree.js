/**
 * Generate a fault tree using AI based on manufacturer, board model, and symptoms.
 * This function calls the server's /ai endpoint to get a customized fault tree.
 */
async function generateAIFaultTree(manufacturer, boardModel, symptoms, measurements = []) {
  const systemPrompt = `You are a BoardScope fault tree generator. You create detailed diagnostic decision trees for PCB board repair.

Return ONLY a JSON object with this exact structure:
{
  "symptom": "Primary symptom description",
  "steps": [
    {
      "text": "Step description",
      "nets": ["NET_NAME1", "NET_NAME2"],
      "hint": "Expected values or additional info",
      "expected_value": "3.3V",
      "tool": "multimeter"
    }
  ]
}

Rules:
- Be specific to the manufacturer and board model
- Include exact net names where possible
- Order steps from most likely/easiest to least likely/hardest
- Include expected values for measurements
- Keep steps actionable and concise`;

  const userPrompt = `Generate a fault tree for:
Manufacturer: ${manufacturer || 'Unknown'}
Board Model: ${boardModel || 'Unknown'}
Symptom: ${symptoms || 'No power'}
Current measurements: ${measurements.length ? JSON.stringify(measurements) : 'None yet'}

Return a JSON fault tree object.`;

  try {
    const response = await fetch('/ai', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        model: null, // Use configured model
        max_tokens: 2000,
        system: systemPrompt,
        messages: [
          { role: 'system', content: systemPrompt },
          { role: 'user', content: userPrompt }
        ]
      })
    });

    const data = await response.json();
    if (data.error) {
      console.error('AI fault tree generation error:', data.error);
      return null;
    }

    const text = data.content?.[0]?.text || '';
    // Parse JSON from response
    const jsonMatch = text.match(/\{[\s\S]*\}/);
    if (jsonMatch) {
      return JSON.parse(jsonMatch[0]);
    }
    return null;
  } catch (error) {
    console.error('Failed to generate AI fault tree:', error);
    return null;
  }
}

